const RARITIES = 4;
const tooltip = (t, i) => `${t.fluff[i]}<br/>${t.desc(t.x[Math.floor(i / RARITIES)])}`;

function writeTexts() {
  const DIR = path.resolve(__dirname, '../../../data/config/gui');
  const xml = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const en = T.english;
  const entry = (guid, enText, text) => [
    '    <Text>',
    `      <GUID>${guid}</GUID>`,
    `      <!-- Text | ${enText} | ${enText} -->`,
    `      <Text>${xml(text)}</Text>`,
    '    </Text>',
  ];
  // every beacon text this script owns, plus the type descriptions of the previous version (7060-065)
  const owned = g => g === GUID.alloc || g === GUID.removedPermit || (g >= 1404007060 && g <= 1404007065) || (g >= GUID.name && g < GUID.tooltip + 30);
  for (const [lang, t] of Object.entries(T)) {
    for (const k of ['names', 'fluff']) if (t[k].length !== 24) throw new Error(`${lang}: ${t[k].length} ${k}`);
    const file = path.join(DIR, `texts_${lang}.xml`);
    const s = fs.readFileSync(file, 'utf8');
    const nl = s.includes('\r\n') ? '\r\n' : '\n';
    const lines = s.split(nl);
    for (let i = lines.length - 1; i >= 0; i--) {
      const m = lines[i].match(/^\s*<GUID>(\d+)<\/GUID>\s*$/);
      if (!m || !owned(+m[1])) continue;
      if (!/^\s*<Text>\s*$/.test(lines[i - 1]) || !/^\s*<\/Text>\s*$/.test(lines[i + 3])) throw new Error(`${lang}: odd block ${m[1]}`);
      lines.splice(i - 1, 5);
    }
    const at = lines.findIndex(l => l.includes(`<GUID>${GUID.lighthouse}</GUID>`));
    if (at < 0 || !/^\s*<\/Text>/.test(lines[at + 3])) throw new Error(`${lang}: ${GUID.lighthouse} layout`);
    lines[at + 1] = `      <!-- Text | ${en.main} | ${en.main} -->`;
    lines[at + 2] = `      <Text>${xml(t.main)}</Text>`;
    const add = [];
    t.names.forEach((n, i) => add.push(...entry(GUID.name + i, en.names[i], n)));
    t.fluff.forEach((f, i) => add.push(...entry(GUID.fluff + i, en.fluff[i], f)));
    t.fluff.forEach((f, i) => add.push(...entry(GUID.tooltip + i, tooltip(en, i), tooltip(t, i))));
    add.push(...entry(GUID.alloc, en.alloc, t.alloc));
    lines.splice(at + 4, 0, ...add);
    fs.writeFileSync(file, lines.join(nl), 'utf8');
  }
  console.log(Object.keys(T).length, 'languages ->', DIR);
}

module.exports = { GUID, T };
if (require.main === module) writeTexts();
